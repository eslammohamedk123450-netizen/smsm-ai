begin;

create table if not exists public.subscription_plans (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  description varchar(500),
  price double precision not null default 0 check (price >= 0),
  billing_period varchar(30) not null default 'monthly',
  monthly_credits integer not null default 0 check (monthly_credits >= 0),
  daily_credits integer not null default 0 check (daily_credits >= 0),
  max_requests integer not null default 0 check (max_requests >= 0),
  features_json text not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.subscription_plans (id, name, description, price, billing_period, monthly_credits, daily_credits, max_requests, features_json, is_active)
values
  (1, 'Free', 'الخطة المجانية', 0, 'monthly', 3000, 100, 10, '{}', true),
  (2, 'Lite', 'الخطة الخفيفة', 4.99, 'monthly', 15000, 500, 50, '{}', true),
  (3, 'Pro', 'الخطة الاحترافية', 14.99, 'monthly', 60000, 2000, 200, '{}', true),
  (4, 'Max', 'الخطة القصوى', 39.99, 'monthly', 300000, 10000, 1000, '{}', true)
on conflict (id) do nothing;

create table if not exists public.system_settings (
  id integer generated by default as identity primary key,
  key varchar(150) not null unique,
  value text not null default '',
  is_sensitive boolean not null default false,
  updated_by integer,
  updated_at timestamptz not null default now()
);

insert into public.system_settings (key, value, is_sensitive)
values ('admob_app_id', '', false)
on conflict (key) do nothing;

alter table public.subscription_plans enable row level security;
alter table public.system_settings enable row level security;

drop policy if exists "Admins manage subscription plans" on public.subscription_plans;
create policy "Admins manage subscription plans"
  on public.subscription_plans
  for all to authenticated
  using (public.suly_is_admin())
  with check (public.suly_is_admin());

drop policy if exists "Admins manage system settings" on public.system_settings;
create policy "Admins manage system settings"
  on public.system_settings
  for all to authenticated
  using (public.suly_is_admin())
  with check (public.suly_is_admin());

revoke all on table public.subscription_plans, public.system_settings from anon;
grant select, update on table public.subscription_plans to authenticated;
grant select, insert, update on table public.system_settings to authenticated;
grant all on table public.subscription_plans, public.system_settings to service_role;

commit;
